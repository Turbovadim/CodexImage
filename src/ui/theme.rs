use gpui::{Hsla, rgb};

pub fn background() -> Hsla {
    rgb(0x0d0e12).into()
}
pub fn raised() -> Hsla {
    rgb(0x14161c).into()
}
pub fn hover() -> Hsla {
    rgb(0x1b1e26).into()
}
pub fn line() -> Hsla {
    rgb(0x262a35).into()
}
pub fn ink() -> Hsla {
    rgb(0xe8eaf0).into()
}
pub fn dim() -> Hsla {
    rgb(0x8b90a0).into()
}
pub fn faint() -> Hsla {
    rgb(0x5a5f6e).into()
}
pub fn accent() -> Hsla {
    rgb(0x7c8cff).into()
}
pub fn accent_strong() -> Hsla {
    rgb(0x5666f7).into()
}
pub fn danger() -> Hsla {
    rgb(0xff6b6b).into()
}
